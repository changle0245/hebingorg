// ============================================================================================
// HTML escape helper for attribute values
// ============================================================================================
const escAttr = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// ============================================================================================
// Apply FAQ AR translations
// ============================================================================================
async function applyFaq(file, html){
  const ar = FAQ_AR[file];
  if(!ar) return html;
  let i = 0;
  // Match opening tag with both data-faq-zh and data-faq-en, no data-faq-ar
  const re = /(<[^>]*?\bdata-faq-(?:zh|en)=("|')(?:(?!\2).)*?\2[^>]*?\bdata-faq-(?:zh|en)=("|')(?:(?!\3).)*?\3)([^>]*>)/g;
  const out = html.replace(re, (full, head, q1, q2, tail) => {
    if(/data-faq-ar=/.test(full)) return full;            // already has ar
    if(i >= ar.length) return full;                       // safety
    const arVal = ar[i++];
    return `${head} data-faq-ar="${escAttr(arVal)}"${tail}`;
  });
  return out;
}

// ============================================================================================
// Apply Tips AR translations: insert <ul class="ar-tips" hidden> after each <ul class="en-tips">.
// We match the en-tips block, replace it with: en-tips block + ar-tips block.
// ============================================================================================
async function applyTips(file, html){
  const ar = TIPS_AR[file];
  if(!ar) return html;
  if(/class=("|')[^"']*\bar-tips\b/.test(html)) return html;  // already injected
  // Find <ul class="en-tips ..."> ... </ul>
  const re = /(<(?:ul|ol)\b[^>]*\bclass=("|')[^"']*\ben-tips\b[^"']*\2[^>]*>)([\s\S]*?)(<\/(?:ul|ol)>)/;
  const m = re.exec(html);
  if(!m) return html;
  const arItems = ar.map(t => `<li>${t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')}</li>`).join('');
  const tag = m[1].includes('<ul') ? 'ul' : 'ol';
  const inject = `\n<!-- ar:auto-translated, review needed -->\n<${tag} class="tips-list ar-tips" hidden>${arItems}</${tag}>`;
  return html.slice(0, m.index + m[0].length) + inject + html.slice(m.index + m[0].length);
}

// ============================================================================================
// Patch setLang() to handle 3 languages properly:
//   - .zh-tips  hidden when lang!=='zh'
//   - .en-tips  hidden when lang!=='en'
//   - .ar-tips  hidden when lang!=='ar'
//   - data-faq-* picks faqAr when lang==='ar'
// We only patch lines that match the specific buggy patterns; idempotent.
// ============================================================================================
async function patchSetLang(file, html){
  let out = html;
  // Pattern 1 (most common, e.g. json-formatter.html line 383-384):
  //   document.querySelectorAll('.zh-tips').forEach(el=>el.classList.toggle('hidden',lang==='en'));
  //   document.querySelectorAll('.en-tips').forEach(el=>el.classList.toggle('hidden',lang!=='en'));
  out = out.replace(
    /document\.querySelectorAll\(\s*('|")\.zh-tips\1\s*\)\.forEach\(\s*el\s*=>\s*el\.classList\.toggle\(\s*('|")hidden\2\s*,\s*lang\s*===\s*('|")en\3\s*\)\s*\)\s*;\s*\n?\s*document\.querySelectorAll\(\s*('|")\.en-tips\4\s*\)\.forEach\(\s*el\s*=>\s*el\.classList\.toggle\(\s*('|")hidden\5\s*,\s*lang\s*!==\s*('|")en\6\s*\)\s*\)\s*;/g,
    `document.querySelectorAll('.zh-tips').forEach(el=>el.hidden=lang!=='zh');\n  document.querySelectorAll('.en-tips').forEach(el=>el.hidden=lang!=='en');\n  document.querySelectorAll('.ar-tips').forEach(el=>el.hidden=lang!=='ar');`
  );

  // Pattern 2: data-faq-* lookup that only handles zh+en, missing ar.
  //   document.querySelectorAll('[data-faq-zh]').forEach(el=>{
  //     el.textContent=lang==='en'?(el.dataset.faqEn||el.dataset.faqZh):el.dataset.faqZh;
  //   });
  out = out.replace(
    /document\.querySelectorAll\(\s*('|")\[data-faq-zh\]\1\s*\)\.forEach\(\s*el\s*=>\s*\{?\s*el\.textContent\s*=\s*lang\s*===\s*('|")en\2\s*\?\s*\(\s*el\.dataset\.faqEn\s*\|\|\s*el\.dataset\.faqZh\s*\)\s*:\s*el\.dataset\.faqZh\s*;?\s*\}?\s*\)\s*;/g,
    `document.querySelectorAll('[data-faq-zh]').forEach(el=>{el.textContent=lang==='ar'?(el.dataset.faqAr||el.dataset.faqEn||el.dataset.faqZh):lang==='en'?(el.dataset.faqEn||el.dataset.faqZh):el.dataset.faqZh;});`
  );

  return out;
}

// ============================================================================================
// Main
// ============================================================================================
const FILES = Object.keys(FAQ_AR);  // 21 files
let stats = { faq: 0, tips: 0, setLang: 0 };

for(const file of FILES){
  const path = join(ROOT, file);
  const before = await readFile(path, 'utf8');
  let after = before;
  const beforeFaq = (after.match(/data-faq-ar=/g) || []).length;
  const beforeTips = (after.match(/\bar-tips\b/g) || []).length;
  const beforeLangPatchedZ = /\.zh-tips'\)\.forEach\(el=>el\.hidden=lang!=='zh'\)/.test(after);

  after = await applyFaq(file, after);
  after = await applyTips(file, after);
  after = await patchSetLang(file, after);

  const afterFaq = (after.match(/data-faq-ar=/g) || []).length;
  const afterTips = (after.match(/\bar-tips\b/g) || []).length;
  const afterLangPatchedZ = /\.zh-tips'\)\.forEach\(el=>el\.hidden=lang!=='zh'\)/.test(after);

  const dFaq = afterFaq - beforeFaq, dTips = afterTips - beforeTips;
  const sl = (afterLangPatchedZ && !beforeLangPatchedZ) ? 1 : 0;
  stats.faq += dFaq; stats.tips += dTips; stats.setLang += sl;

  if(after !== before){
    await writeFile(path, after);
    process.stderr.write(`  ✓ ${file} (faq+${dFaq}, tips+${dTips}, setLang+${sl})\n`);
  } else {
    process.stderr.write(`  - ${file} (no changes)\n`);
  }
}

process.stderr.write(`\nSummary: ${stats.faq} FAQ entries, ${stats.tips} tips refs, ${stats.setLang} setLang patches\n`);
